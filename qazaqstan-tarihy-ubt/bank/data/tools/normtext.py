# -*- coding: utf-8 -*-
import re
CYR = 'А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі'
# Латын әріптері кирилл сөздерінің ішінде кездеседі (дереккөздегі
# PDF-конверсия/көшіруден қорғау артефактісі). Оларды кириллге келтіреміз.
# V әрпі рим цифры болғандықтан тізімге кірмейді.
MAP = {'i':'і','h':'һ','o':'о','a':'а','c':'с','e':'е','p':'р','x':'х','y':'у',
       'O':'О','A':'А','M':'М','K':'К','T':'Т','P':'Р','C':'С','I':'І',
       'B':'В','E':'Е','H':'Н','X':'Х','Y':'У'}

def fix(t):
    if not t:
        return t
    t = t.replace('ӛ','ө').replace('Ӛ','Ө')
    def r(m):
        return MAP.get(m.group(1), m.group(1))
    # латын әрпі + кирилл әрпі (алдында латын әрпі жоқ)
    t = re.sub(rf'(?<![A-Za-z])([A-Za-z])(?=[{CYR}])', r, t)
    # кирилл әрпі + латын әрпі + кирилл әрпі
    t = re.sub(rf'(?<=[{CYR}])([A-Za-z])(?=[{CYR}])', r, t)
    # кирилл сөзінің соңындағы жалғыз латын i / h
    t = re.sub(rf'(?<=[{CYR}])([ih])(?![A-Za-z])', r, t)
    return t
